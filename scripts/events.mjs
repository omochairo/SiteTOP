// include: 記事の題名にどれか 1 つでも入っていれば候補
// exclude: 題名に入っていたら除く（別の行事の記事の取り違えを防ぐ）
// extra: 記事が少ない行事に添える、おもちゃいろのツールなど（固定）

const fixed = (m, d) => (y) => new Date(Date.UTC(y, m - 1, d));
// m 月の第 n 週の曜日 wd（0=日）
const nthWeekday = (m, n, wd) => (y) => {
  const first = new Date(Date.UTC(y, m - 1, 1)).getUTCDay();
  const day = 1 + ((wd - first + 7) % 7) + (n - 1) * 7;
  return new Date(Date.UTC(y, m - 1, day));
};

